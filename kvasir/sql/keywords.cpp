std::string upper(std::string_view word) {
  std::string out(word);
  for (auto& c : out) c = static_cast<char>(std::toupper(static_cast<unsigned char>(c)));
  return out;
}

bool same_word(std::string_view a, std::string_view b) noexcept {
  if (a.size() != b.size()) return false;
  for (size_t i = 0; i < a.size(); ++i)
    if (std::toupper(static_cast<unsigned char>(a[i])) != std::toupper(static_cast<unsigned char>(b[i]))) return false;
  return true;
}

bool is_reserved(std::string_view word) noexcept {
  if (word.empty() || word.size() > 24) return false;
  char buffer[24];
  for (size_t i = 0; i < word.size(); ++i) buffer[i] = static_cast<char>(std::toupper(static_cast<unsigned char>(word[i])));
  return std::binary_search(reserved.begin(), reserved.end(), std::string_view(buffer, word.size()));
}

