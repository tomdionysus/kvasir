// kvasir-ducet: compiles Unicode's collation element table (allkeys.txt) into
// C++ tables at build time (ruling 32).
//
//   kvasir-ducet allkeys-9.0.0.txt ducet_table.cpp
//
// Each entry is one code point, or a contraction of two or three, with its
// collation elements; entries are sorted by their code points so a lookup can
// search. The variable-weighting mark ("*") is dropped: MySQL's 0900
// collations weigh every character. Exits 1 with a message for a line it
// cannot read.

#include <algorithm>
#include <cstdint>
#include <fstream>
#include <iostream>
#include <sstream>
#include <string>
#include <vector>

namespace {

struct Element {
  uint32_t primary, secondary, tertiary;
};

struct Entry {
  std::vector<uint32_t> code_points;
  std::vector<Element> elements;
};

uint32_t hex(const std::string& s) { return static_cast<uint32_t>(std::stoul(s, nullptr, 16)); }

}  // namespace

int main(int argc, char** argv) {
  if (argc != 3) {
    std::cerr << "usage: kvasir-ducet allkeys.txt output.cpp" << std::endl;
    return 2;
  }
  std::ifstream in(argv[1]);
  if (!in) {
    std::cerr << "kvasir-ducet: cannot read " << argv[1] << std::endl;
    return 1;
  }
  std::vector<Entry> entries;
  std::string line;
  size_t number = 0;
  while (std::getline(in, line)) {
    ++number;
    const auto hash = line.find('#');
    if (hash != std::string::npos) line.erase(hash);
    if (line.find_first_not_of(" \t\r") == std::string::npos || line[0] == '@') continue;
    const auto semicolon = line.find(';');
    if (semicolon == std::string::npos) {
      std::cerr << "kvasir-ducet: line " << number << " has no ';'" << std::endl;
      return 1;
    }
    Entry e;
    std::istringstream points(line.substr(0, semicolon));
    std::string point;
    while (points >> point) e.code_points.push_back(hex(point));
    // Elements: [.PPPP.SSSS.TTTT] or [*PPPP.SSSS.TTTT].
    std::string rest = line.substr(semicolon + 1);
    for (size_t open = rest.find('['); open != std::string::npos; open = rest.find('[', open + 1)) {
      const auto close = rest.find(']', open);
      const std::string body = rest.substr(open + 2, close - open - 2);
      const auto dot1 = body.find('.');
      const auto dot2 = body.find('.', dot1 + 1);
      e.elements.push_back({hex(body.substr(0, dot1)), hex(body.substr(dot1 + 1, dot2 - dot1 - 1)), hex(body.substr(dot2 + 1))});
    }
    if (e.code_points.empty() || e.code_points.size() > 3 || e.elements.empty()) {
      std::cerr << "kvasir-ducet: line " << number << " is not one to three code points with elements" << std::endl;
      return 1;
    }
    entries.push_back(std::move(e));
  }
  std::sort(entries.begin(), entries.end(), [](const Entry& a, const Entry& b) { return a.code_points < b.code_points; });

  std::ofstream out(argv[2]);
  out << "// Generated by kvasir-ducet from Unicode's allkeys.txt; do not edit.\n"
         "#include \"kvasir/exec/ducet.h\"\n"
         "namespace kvasir::exec::ducet {\n"
         "const Element elements[] = {\n";
  size_t offset = 0;
  for (const auto& e : entries)
    for (const auto& el : e.elements) {
      out << "{" << el.primary << "," << el.secondary << "," << el.tertiary << "},\n";
      ++offset;
    }
  out << "};\nconst Entry entries[] = {\n";
  offset = 0;
  for (const auto& e : entries) {
    out << "{" << e.code_points[0] << "," << (e.code_points.size() > 1 ? e.code_points[1] : 0) << "," << (e.code_points.size() > 2 ? e.code_points[2] : 0)
        << "," << offset << "," << e.elements.size() << "},\n";
    offset += e.elements.size();
  }
  out << "};\nconst size_t entry_count = " << entries.size() << ";\n}  // namespace kvasir::exec::ducet\n";
  if (!out) {
    std::cerr << "kvasir-ducet: cannot write " << argv[2] << std::endl;
    return 1;
  }
  return 0;
}
