// kvasir-general-ci: derives the general_ci collations' weights from
// Unicode 3.0.0's UnicodeData.txt at build time (ruling 33).
//
//   kvasir-general-ci UnicodeData-3.0.0.txt general_ci_table.cpp
//
// One weight per BMP code point, the rule found by checking every one of
// them against MySQL 8.4's WEIGHT_STRING() on the reference server:
//
// - in Latin, Greek and Cyrillic (below U+0530, and U+1E00 to U+1FFF), a
//   character with a canonical decomposition weighs as the first character
//   of it, taken in full but never through a one-character decomposition,
//   when that first character is a letter: accents are stripped;
// - then the weight is the character's uppercase, if Unicode 3.0 gives one;
// - three exceptions, as observed: U+00DF (sharp s) weighs as S, and
//   U+0419 and U+0439 (short i) keep their breve.
//
// Exits 1 with a message for a line it cannot read.

#include <cstdint>
#include <fstream>
#include <iostream>
#include <sstream>
#include <string>
#include <unordered_map>
#include <vector>

namespace {

struct Character {
  std::string category;
  std::vector<uint32_t> decomposition;  // canonical only; empty otherwise
  uint32_t upper = 0;                   // 0 for none
};

std::unordered_map<uint32_t, Character> characters;

// The full canonical decomposition, never through a one-character one.
std::vector<uint32_t> decompose(uint32_t cp) {
  const auto it = characters.find(cp);
  if (it == characters.end() || it->second.decomposition.size() < 2) return {cp};
  std::vector<uint32_t> out;
  for (const uint32_t part : it->second.decomposition) {
    const auto more = decompose(part);
    out.insert(out.end(), more.begin(), more.end());
  }
  return out;
}

bool letter(uint32_t cp) {
  const auto it = characters.find(cp);
  return it != characters.end() && !it->second.category.empty() && it->second.category[0] == 'L';
}

uint32_t weight(uint32_t cp) {
  if (cp == 0x00DF) return 0x0053;
  uint32_t base = cp;
  const bool european = cp < 0x0530 || (cp >= 0x1E00 && cp < 0x2000);
  if (european && cp != 0x0419 && cp != 0x0439) {
    const auto d = decompose(cp);
    if (letter(d[0])) base = d[0];
  }
  const auto it = characters.find(base);
  return it != characters.end() && it->second.upper ? it->second.upper : base;
}

}  // namespace

int main(int argc, char** argv) {
  if (argc != 3) {
    std::cerr << "usage: kvasir-general-ci UnicodeData.txt output.cpp" << std::endl;
    return 2;
  }
  std::ifstream in(argv[1]);
  if (!in) {
    std::cerr << "kvasir-general-ci: cannot read " << argv[1] << std::endl;
    return 1;
  }
  std::string line;
  size_t number = 0;
  while (std::getline(in, line)) {
    ++number;
    std::vector<std::string> fields;
    std::istringstream split(line);
    std::string field;
    while (std::getline(split, field, ';')) fields.push_back(field);
    if (fields.size() < 13) {
      std::cerr << "kvasir-general-ci: line " << number << " has fewer than 13 fields" << std::endl;
      return 1;
    }
    try {
      Character c;
      c.category = fields[2];
      if (!fields[5].empty() && fields[5][0] != '<') {
        std::istringstream parts(fields[5]);
        std::string part;
        while (parts >> part) c.decomposition.push_back(static_cast<uint32_t>(std::stoul(part, nullptr, 16)));
      }
      if (!fields[12].empty()) c.upper = static_cast<uint32_t>(std::stoul(fields[12], nullptr, 16));
      characters[static_cast<uint32_t>(std::stoul(fields[0], nullptr, 16))] = std::move(c);
    } catch (const std::exception&) {
      std::cerr << "kvasir-general-ci: line " << number << " has a field that is not hexadecimal" << std::endl;
      return 1;
    }
  }

  std::ofstream out(argv[2]);
  out << "// Generated by kvasir-general-ci from Unicode's UnicodeData-3.0.0.txt; do not edit.\n"
         "#include \"kvasir/exec/general_ci_table.h\"\n"
         "namespace kvasir::exec::general_ci {\n"
         "const uint16_t weights[65536] = {\n";
  for (uint32_t cp = 0; cp < 0x10000; ++cp) out << weight(cp) << (cp % 16 == 15 ? ",\n" : ",");
  out << "};\n}  // namespace kvasir::exec::general_ci\n";
  if (!out) {
    std::cerr << "kvasir-general-ci: cannot write " << argv[2] << std::endl;
    return 1;
  }
  return 0;
}
