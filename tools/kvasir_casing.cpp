// kvasir-casing: compiles a UnicodeData.txt's simple case mappings into a
// table at build time, for UPPER() and LOWER().
//
//   kvasir-casing UnicodeData.txt <limit, hex> <name> output.cpp
//
// One entry per code point below the limit whose simple uppercase or
// lowercase (fields 12 and 13) differs from it, in code point order. MySQL
// 8.4 maps with Unicode 9.0.0's under utf8mb4's 0900 collations and
// utf8mb4_bin, and with Unicode 3.0.0's, in the BMP only, under the
// general_ci and utf8mb3 collations (checked for every code point against
// the reference server). Exits 1 with a message for a line it cannot read.

#include <cstdint>
#include <fstream>
#include <iostream>
#include <sstream>
#include <string>
#include <vector>

int main(int argc, char** argv) {
  if (argc != 5) {
    std::cerr << "usage: kvasir-casing UnicodeData.txt limit name output.cpp" << std::endl;
    return 2;
  }
  std::ifstream in(argv[1]);
  if (!in) {
    std::cerr << "kvasir-casing: cannot read " << argv[1] << std::endl;
    return 1;
  }
  const auto limit = std::stoul(argv[2], nullptr, 16);
  const std::string name = argv[3];
  struct Pair {
    unsigned long code, upper, lower;
  };
  std::vector<Pair> pairs;
  std::string line;
  size_t number = 0;
  while (std::getline(in, line)) {
    ++number;
    std::vector<std::string> fields;
    std::istringstream split(line);
    std::string field;
    while (std::getline(split, field, ';')) fields.push_back(field);
    if (fields.size() < 13) {
      std::cerr << "kvasir-casing: line " << number << " has fewer than 13 fields" << std::endl;
      return 1;
    }
    try {
      const auto code = std::stoul(fields[0], nullptr, 16);
      if (code >= limit) continue;
      const auto upper = fields[12].empty() ? code : std::stoul(fields[12], nullptr, 16);
      const auto lower = fields.size() > 13 && !fields[13].empty() ? std::stoul(fields[13], nullptr, 16) : code;
      if (upper != code || lower != code) pairs.push_back({code, upper, lower});
    } catch (const std::exception&) {
      std::cerr << "kvasir-casing: line " << number << " has a field that is not hexadecimal" << std::endl;
      return 1;
    }
  }
  std::ofstream out(argv[4]);
  out << "// Generated by kvasir-casing from Unicode's " << argv[1] << "; do not edit.\n"
      << "#include \"kvasir/exec/casing_table.h\"\n"
         "namespace kvasir::exec::casing {\n"
         "const CasePair "
      << name << "[] = {\n";
  for (const auto& p : pairs) out << "{0x" << std::hex << p.code << ",0x" << p.upper << ",0x" << p.lower << "},\n";
  out << std::dec << "};\nconst size_t " << name << "_size = " << pairs.size() << ";\n}  // namespace kvasir::exec::casing\n";
  if (!out) {
    std::cerr << "kvasir-casing: cannot write " << argv[4] << std::endl;
    return 1;
  }
  return 0;
}
